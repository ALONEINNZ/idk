        #region Safety and Validation
        
        private bool CanPlayerPerformAction(BasePlayer player)
        {
            if (player == null || !player.IsConnected) return false;
            
            ulong playerId = player.userID;
            
            if (lastActionTime.ContainsKey(playerId))
            {
                if (Time.time - lastActionTime[playerId] < ACTION_COOLDOWN)
                {
                    return false;
                }
            }
            
            if (processingPlayers.Contains(playerId))
            {
                return false;
            }
            
            return true;
        }
        
        private void StartPlayerAction(BasePlayer player)
        {
            if (player == null) return;
            
            ulong playerId = player.userID;
            lastActionTime[playerId] = Time.time;
            processingPlayers.Add(playerId);
            
            var data = GetPlayerData(playerId);
            if (data != null)
            {
                data.IsProcessing = true;
                data.LastActionTime = Time.time;
            }
        }
        
        private void EndPlayerAction(BasePlayer player)
        {
            if (player == null) return;
            
            ulong playerId = player.userID;
            processingPlayers.Remove(playerId);
            
            var data = GetPlayerData(playerId);
            if (data != null)
            {
                data.IsProcessing = false;
            }
        }
        
        private bool IsValidPosition(Vector3 position)
        {
            if (float.IsNaN(position.x) || float.IsNaN(position.y) || float.IsNaN(position.z))
                return false;
            
            if (float.IsInfinity(position.x) || float.IsInfinity(position.y) || float.IsInfinity(position.z))
                return false;
            
            if (Mathf.Abs(position.x) > 10000f || Mathf.Abs(position.z) > 10000f)
                return false;
            
            if (position.y < -1000f || position.y > 1000f)
                return false;
            
            return true;
        }
        
        private Vector3 GetSafePosition(Vector3 position)
        {
            if (IsValidPosition(position))
                return position;
            
            return config.LobbySpawnPoint != Vector3.zero ? config.LobbySpawnPoint : Vector3.zero;
        }
        
        private void PerformCleanup()
        {
            try
            {
                CleanupExpiredQueues();
                CleanupInactiveMatches();
                CleanupDisconnectedPlayers();
                CleanupOrphanedTimers();
            }
            catch (Exception ex)
            {
                PrintError($"Error during cleanup: {ex.Message}");
            }
        }
        
        private void CleanupExpiredQueues()
        {
            foreach (var kvp in queueZones)
            {
                var zone = kvp.Value;
                var expiredPlayers = new List<ulong>();
                
                foreach (var playerId in zone.QueuedPlayers)
                {
                    var data = GetPlayerData(playerId);
                    if (data == null || !data.IsInQueue || 
                        (data.QueueJoinTime > 0 && Time.time - data.QueueJoinTime > config.MaxQueueTime))
                    {
                        expiredPlayers.Add(playerId);
                    }
                }
                
                foreach (var playerId in expiredPlayers)
                {
                    zone.QueuedPlayers.Remove(playerId);
                    var data = GetPlayerData(playerId);
                    if (data != null)
                    {
                        data.IsInQueue = false;
                        data.QueueZoneName = "";
                    }
                }
            }
        }
        
        private void CleanupInactiveMatches()
        {
            var inactiveMatches = new List<ulong>();
            
            foreach (var kvp in activeMatches)
            {
                var match = kvp.Value;
                
                if (Time.time - match.MatchStartTime > 3600f)
                {
                    inactiveMatches.Add(kvp.Key);
                    continue;
                }
                
                var connectedPlayers = match.TerroristPlayers.Concat(match.CounterTerroristPlayers)
                    .Count(id => BasePlayer.FindByID(id) != null);
                
                if (connectedPlayers == 0)
                {
                    inactiveMatches.Add(kvp.Key);
                }
            }
            
            foreach (var matchId in inactiveMatches)
            {
                if (activeMatches.ContainsKey(matchId))
                {
                    EndMatch(activeMatches[matchId], "Match cleanup - inactive");
                }
            }
        }
        
        private void CleanupDisconnectedPlayers()
        {
            var disconnectedPlayers = new List<ulong>();
            
            foreach (var kvp in playerData)
            {
                var playerId = kvp.Key;
                var data = kvp.Value;
                
                var player = BasePlayer.FindByID(playerId);
                if (player == null || !player.IsConnected)
                {
                    if (data.CurrentMatchId != 0)
                    {
                        if (activeMatches.ContainsKey(data.CurrentMatchId))
                        {
                            var match = activeMatches[data.CurrentMatchId];
                            match.TerroristPlayers.Remove(playerId);
                            match.CounterTerroristPlayers.Remove(playerId);
                        }
                    }
                    
                    if (data.IsInQueue && !string.IsNullOrEmpty(data.QueueZoneName))
                    {
                        if (queueZones.ContainsKey(data.QueueZoneName))
                        {
                            queueZones[data.QueueZoneName].QueuedPlayers.Remove(playerId);
                        }
                    }
                    
                    data.DefuseTimer?.Destroy();
                    disconnectedPlayers.Add(playerId);
                }
            }
            
            foreach (var playerId in disconnectedPlayers)
            {
                playerData.Remove(playerId);
            }
        }
        
