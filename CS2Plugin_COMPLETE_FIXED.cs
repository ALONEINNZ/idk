        private void SwitchToNextSpectatorTarget(BasePlayer spectator, PlayerData spectatorData)
        {
            try
            {
                if (spectatorData.CurrentMatchId == 0 || !activeMatches.ContainsKey(spectatorData.CurrentMatchId))
                {
                    return;
                }
                
                var match = activeMatches[spectatorData.CurrentMatchId];
                var allPlayers = match.TerroristPlayers.Concat(match.CounterTerroristPlayers).ToList();
                
                var alivePlayers = new List<ulong>();
                foreach (var playerId in allPlayers)
                {
                    var player = BasePlayer.FindByID(playerId);
                    if (player != null && player.IsConnected && !player.IsDead())
                    {
                        alivePlayers.Add(playerId);
                    }
                }
                
                if (alivePlayers.Count == 0)
                {
                    spectatorData.IsInFreeCam = true;
                    spectatorData.SpectatingPlayerId = 0;
                    return;
                }
                
                int currentIndex = alivePlayers.IndexOf(spectatorData.SpectatingPlayerId);
                int nextIndex = (currentIndex + 1) % alivePlayers.Count;
                
                spectatorData.SpectatingPlayerId = alivePlayers[nextIndex];
                spectatorData.SpectatorIndex = nextIndex;
                
                var nextPlayer = BasePlayer.FindByID(spectatorData.SpectatingPlayerId);
                if (nextPlayer != null)
                {
                    SendReply(spectator, $"Now spectating: {nextPlayer.displayName}");
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error switching spectator target: {ex.Message}");
            }
        }
        
