            {
                RoundTimer?.Destroy();
                BuyPhaseTimer?.Destroy();
                PlantedBomb?.ExplosionTimer?.Destroy();
                
                foreach (var timer in ActiveTimers)
                {
                    timer?.Destroy();
                }
                ActiveTimers.Clear();
            }
