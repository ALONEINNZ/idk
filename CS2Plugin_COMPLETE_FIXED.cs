        private void LoadData()
        {
            try
            {
                playerData = Interface.Oxide.DataFileSystem.ReadObject<Dictionary<ulong, PlayerData>>("CS2Plugin_PlayerData") ?? new Dictionary<ulong, PlayerData>();
                queueZones = Interface.Oxide.DataFileSystem.ReadObject<Dictionary<string, QueueZone>>("CS2Plugin_QueueZones") ?? new Dictionary<string, QueueZone>();
                bombSites = Interface.Oxide.DataFileSystem.ReadObject<Dictionary<string, BombSite>>("CS2Plugin_BombSites") ?? new Dictionary<string, BombSite>();
                mapConfigurations = Interface.Oxide.DataFileSystem.ReadObject<Dictionary<string, MapConfiguration>>("CS2Plugin_MapConfigurations") ?? new Dictionary<string, MapConfiguration>();
                
                ValidateLoadedData();
            }
            catch (Exception ex)
            {
                PrintError($"Error loading data: {ex.Message}");
                playerData = new Dictionary<ulong, PlayerData>();
                queueZones = new Dictionary<string, QueueZone>();
                bombSites = new Dictionary<string, BombSite>();
                mapConfigurations = new Dictionary<string, MapConfiguration>();
            }
        }
        
        private void ValidateLoadedData()
        {
            var invalidPlayers = playerData.Where(kvp => !kvp.Value.IsValid()).Select(kvp => kvp.Key).ToList();
            foreach (var playerId in invalidPlayers)
            {
                playerData.Remove(playerId);
                PrintWarning($"Removed invalid player data for {playerId}");
            }
            
            var invalidZones = queueZones.Where(kvp => !kvp.Value.IsValid()).Select(kvp => kvp.Key).ToList();
            foreach (var zoneName in invalidZones)
            {
                queueZones.Remove(zoneName);
                PrintWarning($"Removed invalid queue zone: {zoneName}");
            }
            
            var invalidSites = bombSites.Where(kvp => !kvp.Value.IsValid()).Select(kvp => kvp.Key).ToList();
            foreach (var siteName in invalidSites)
            {
                bombSites.Remove(siteName);
                PrintWarning($"Removed invalid bomb site: {siteName}");
            }
            
            var invalidMaps = mapConfigurations.Where(kvp => !kvp.Value.IsValid()).Select(kvp => kvp.Key).ToList();
            foreach (var mapName in invalidMaps)
            {
                mapConfigurations.Remove(mapName);
                PrintWarning($"Removed invalid map configuration: {mapName}");
            }
        }
        
        private void SaveData()
        {
            try
            {
                Interface.Oxide.DataFileSystem.WriteObject("CS2Plugin_PlayerData", playerData);
                Interface.Oxide.DataFileSystem.WriteObject("CS2Plugin_QueueZones", queueZones);
                Interface.Oxide.DataFileSystem.WriteObject("CS2Plugin_BombSites", bombSites);
                Interface.Oxide.DataFileSystem.WriteObject("CS2Plugin_MapConfigurations", mapConfigurations);
            }
            catch (Exception ex)
            {
                PrintError($"Error saving data: {ex.Message}");
            }
        }
        
        private PlayerData GetPlayerData(ulong playerId)
        {
            if (playerId == 0) return null;
            
            if (!playerData.ContainsKey(playerId))
            {
                var player = BasePlayer.FindByID(playerId);
                if (player == null) return null;
                
                playerData[playerId] = new PlayerData
                {
                    PlayerId = playerId,
                    PlayerName = player.displayName ?? "Unknown",
                    SafePosition = player.transform.position
                };
            }
            return playerData[playerId];
        }
        
