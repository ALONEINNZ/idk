        private Vector3 GetRandomPositionInRadius(Vector3 center, float radius)
        {
            float angle = UnityEngine.Random.Range(0f, 360f) * Mathf.Deg2Rad;
            float distance = UnityEngine.Random.Range(0f, radius);
            
            return new Vector3(
                center.x + Mathf.Cos(angle) * distance,
                center.y,
                center.z + Mathf.Sin(angle) * distance
            );
        }
        
        private float GetTerrainHeight(Vector3 position)
        {
            try
            {
                if (TerrainMeta.HeightMap != null)
                {
                    return TerrainMeta.HeightMap.GetHeight(position);
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error getting terrain height: {ex.Message}");
            }
            
            try
            {
                RaycastHit hit;
                if (Physics.Raycast(position + Vector3.up * 200f, Vector3.down, out hit, 400f))
                {
                    return hit.point.y;
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error with raycast terrain height: {ex.Message}");
            }
            
            return 0f;
        }
        
