        private void CmdSpectatePrevious(BasePlayer player, string command, string[] args)
        {
            if (!permission.UserHasPermission(player.UserIDString, PERMISSION_USE))
            {
                SendReply(player, "You don't have permission to use this command!");
                return;
            }
            
            try
            {
                var data = GetPlayerData(player.userID);
                if (data == null || !data.IsSpectating) return;
                
                if (data.CurrentMatchId == 0 || !activeMatches.ContainsKey(data.CurrentMatchId))
                {
                    return;
                }
                
                var match = activeMatches[data.CurrentMatchId];
                var allPlayers = match.TerroristPlayers.Concat(match.CounterTerroristPlayers).ToList();
                
                var alivePlayers = new List<ulong>();
                foreach (var playerId in allPlayers)
                {
                    var p = BasePlayer.FindByID(playerId);
                    if (p != null && p.IsConnected && !p.IsDead())
                    {
                        alivePlayers.Add(playerId);
                    }
                }
                
                if (alivePlayers.Count == 0)
                {
                    data.IsInFreeCam = true;
                    data.SpectatingPlayerId = 0;
                    return;
                }
                
                int currentIndex = alivePlayers.IndexOf(data.SpectatingPlayerId);
                int prevIndex = currentIndex <= 0 ? alivePlayers.Count - 1 : currentIndex - 1;
                
                data.SpectatingPlayerId = alivePlayers[prevIndex];
                data.SpectatorIndex = prevIndex;
                
                var prevPlayer = BasePlayer.FindByID(data.SpectatingPlayerId);
                if (prevPlayer != null)
                {
                    SendReply(player, $"Now spectating: {prevPlayer.displayName}");
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error switching to previous spectator target: {ex.Message}");
            }
        }
        
