            public float MatchStartTime { get; set; } = 0f;
            public List<Timer> ActiveTimers { get; set; } = new List<Timer>();
            
            public bool IsValid()
            {
                return MatchId != 0 && 
                       TerroristPlayers.Count > 0 && 
                       CounterTerroristPlayers.Count > 0 &&
