        private void CheckRoundEndConditions(Match match)
        {
            try
            {
                int aliveTerrorists = CountAlivePlayers(match.TerroristPlayers);
                int aliveCounterTerrorists = CountAlivePlayers(match.CounterTerroristPlayers);
                
                if (aliveTerrorists == 0)
                {
                    EndRound(match, RoundEndReason.TerroristsEliminated);
                }
                else if (aliveCounterTerrorists == 0)
                {
                    if (match.PlantedBomb != null)
                    {
                        return;
                    }
                    else
                    {
                        EndRound(match, RoundEndReason.CounterTerroristsEliminated);
                    }
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error checking round end conditions: {ex.Message}");
            }
        }
        
        private int CountAlivePlayers(List<ulong> playerIds)
        {
            int count = 0;
            foreach (var playerId in playerIds)
            {
                var player = BasePlayer.FindByID(playerId);
                if (player != null && player.IsConnected && !player.IsDead())
                {
                    count++;
                }
            }
            return count;
        }
        
        private void UpdateBombTimer(Match match)
        {
            try
            {
                if (match.PlantedBomb == null) return;
                
                float timeLeft = match.PlantedBomb.GetTimeLeft(config.BombTimer);
                
                if (timeLeft <= 0)
                {
                    ExplodeBomb(match);
                }
            }
            catch (Exception ex)
