        private void UpdatePlayerSpectating(BasePlayer spectator, PlayerData spectatorData)
        {
            try
            {
                var spectatedPlayer = BasePlayer.FindByID(spectatorData.SpectatingPlayerId);
                
                if (spectatedPlayer == null || !spectatedPlayer.IsConnected || spectatedPlayer.IsDead())
                {
                    SwitchToNextSpectatorTarget(spectator, spectatorData);
                    return;
                }
                
                Vector3 spectatorPos = spectatedPlayer.transform.position + Vector3.up * 2f;
                if (IsValidPosition(spectatorPos))
                {
