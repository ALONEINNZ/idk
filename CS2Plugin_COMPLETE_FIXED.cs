            }
        }
        
        private void ExplodeBomb(Match match)
        {
            try
            {
                if (match.PlantedBomb == null) return;
                
                Vector3 bombPos = match.PlantedBomb.Position;
                
                var nearbyPlayers = new List<BasePlayer>();
                Vis.Entities(bombPos, 20f, nearbyPlayers);
                
                foreach (var player in nearbyPlayers)
                {
                    if (player != null && !player.IsDead())
                    {
                        float distance = Vector3.Distance(player.transform.position, bombPos);
                        float damage = Mathf.Lerp(100f, 20f, distance / 20f);
                        player.Hurt(damage);
                    }
                }
                
                EndRound(match, RoundEndReason.BombExploded);
                
                PrintWarning($"Bomb exploded in match {match.MatchId}");
            }
            catch (Exception ex)
            {
                PrintError($"Error exploding bomb: {ex.Message}");
            }
        }
        
