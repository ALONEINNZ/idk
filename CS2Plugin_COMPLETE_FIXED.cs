        private void CmdTeleportToMap(BasePlayer player, string command, string[] args)
        {
            if (!permission.UserHasPermission(player.UserIDString, PERMISSION_ADMIN))
            {
                SendReply(player, "You don't have permission to use this command!");
                return;
            }
            
            if (args.Length < 1)
            {
                SendReply(player, "Usage: /teleportmap <mapname>");
                return;
            }
            
            try
            {
                string mapName = args[0];
                
                if (!mapConfigurations.ContainsKey(mapName))
                {
                    SendReply(player, $"Map '{mapName}' not found!");
                    return;
                }
                
                var mapConfig = mapConfigurations[mapName];
                Vector3 teleportPos = mapConfig.SpectatorArea;
                
                if (teleportPos == Vector3.zero && mapConfig.TerroristSpawns.Count > 0)
                {
                    teleportPos = mapConfig.TerroristSpawns[0] + Vector3.up * 10f;
                }
                
                TeleportPlayerSafely(player, teleportPos);
                SendReply(player, $"Teleported to map '{mapName}'!");
            }
            catch (Exception ex)
            {
                PrintError($"Error teleporting to map: {ex.Message}");
                SendReply(player, "Error teleporting to map!");
            }
        }
        
