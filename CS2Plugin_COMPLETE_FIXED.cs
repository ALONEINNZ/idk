        private QueueZone FindNearestQueueZone(Vector3 position)
        {
            QueueZone nearest = null;
            float nearestDistance = float.MaxValue;
            
            foreach (var zone in queueZones.Values)
            {
                if (!zone.IsActive) continue;
                
                Vector3 zoneCenter = zone.GetCenter();
                float distance = Vector3.Distance(position, zoneCenter);
                
                if (distance < nearestDistance)
                {
                    nearestDistance = distance;
                    nearest = zone;
                }
            }
            
            return nearest;
        }
        
