        private void InitializeTimers()
        {
            uiUpdateTimer = timer.Every(2f, UpdateAllUI);
            matchUpdateTimer = timer.Every(0.5f, UpdateMatches);
            cleanupTimer = timer.Every(config.AutoCleanupInterval, PerformCleanup);
        }
        
        void OnServerInitialized()
        {
            try
            {
                LoadData();
                InitializeDefaultMaps();
                
                if (config.GenerateMapOnStart)
                {
                    timer.Once(10f, () => SafeAutoGenerateServerMaps());
                }
                
                if (config.AutoDetectMapCenter)
                {
                    DetectMapCenter();
                }
                
                PrintWarning("CS2 Style Plugin loaded successfully!");
                PrintWarning($"Map generation center: {config.MapGenerationCenter}");
                PrintWarning($"Available maps: {mapConfigurations.Count}");
                PrintWarning($"Large map mode: {config.LargeMapMode}");
            }
            catch (Exception ex)
            {
                PrintError($"Error during server initialization: {ex.Message}");
            }
        }
        
        void Unload()
        {
            try
            {
                SaveData();
                CleanupAllResources();
                PrintWarning("CS2 Style Plugin unloaded successfully!");
            }
            catch (Exception ex)
            {
                PrintError($"Error during plugin unload: {ex.Message}");
            }
        }
        
        private void CleanupAllResources()
        {
            uiUpdateTimer?.Destroy();
            matchUpdateTimer?.Destroy();
            cleanupTimer?.Destroy();
            
            foreach (var match in activeMatches.Values.ToList())
            {
                try
                {
                    EndMatch(match, "Plugin unloaded");
                }
                catch (Exception ex)
                {
                    PrintError($"Error ending match {match.MatchId}: {ex.Message}");
                }
            }
            
            foreach (var data in playerData.Values)
            {
                try
                {
                    data.DefuseTimer?.Destroy();
                }
                catch (Exception ex)
                {
                    PrintError($"Error cleaning up player {data.PlayerId}: {ex.Message}");
                }
            }
            
            foreach (var player in BasePlayer.activePlayerList)
            {
                try
                {
                    DestroyUI(player);
                }
                catch (Exception ex)
                {
                    PrintError($"Error destroying UI for {player.displayName}: {ex.Message}");
                }
            }
            
            processingPlayers.Clear();
            lastActionTime.Clear();
        }
        
