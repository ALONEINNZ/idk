        }
        
        private void CheckQueueZoneInteraction(BasePlayer player, PlayerData data)
        {
            try
            {
                Vector3 playerPos = player.transform.position;
                
                foreach (var kvp in queueZones)
                {
                    var zone = kvp.Value;
                    if (!zone.IsActive) continue;
                    
                    bool isInZone = IsPlayerInZone(playerPos, zone.MinBounds, zone.MaxBounds);
                    
                    if (isInZone && !data.IsInQueue && data.CurrentMatchId == 0)
                    {
                        TryAddPlayerToQueue(player, zone);
                    }
                    else if (!isInZone && data.IsInQueue && data.QueueZoneName == zone.Name)
                    {
                        RemovePlayerFromQueue(player, data);
                        SendReply(player, "You left the queue zone and have been removed from the queue.");
                    }
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error checking queue zone interaction: {ex.Message}");
            }
        }
        
        private bool IsPlayerInZone(Vector3 position, Vector3 minBounds, Vector3 maxBounds)
        {
            return position.x >= minBounds.x && position.x <= maxBounds.x &&
                   position.y >= minBounds.y && position.y <= maxBounds.y &&
                   position.z >= minBounds.z && position.z <= maxBounds.z;
        }
        
        private void TryAddPlayerToQueue(BasePlayer player, QueueZone zone)
        {
            try
            {
                if (!CanPlayerPerformAction(player)) return;
                
                StartPlayerAction(player);
                
                var data = GetPlayerData(player.userID);
                if (data == null)
                {
                    EndPlayerAction(player);
                    return;
                }
                
                if (zone.QueuedPlayers.Count >= zone.TeamSize * 2)
                {
                    SendReply(player, "Queue is full!");
                    EndPlayerAction(player);
                    return;
                }
                
                if (!zone.QueuedPlayers.Contains(player.userID))
                {
                    zone.QueuedPlayers.Add(player.userID);
                    data.IsInQueue = true;
                    data.QueueZoneName = zone.Name;
                    data.QueueJoinTime = Time.time;
                    
                    SendReply(player, $"Added to queue ({zone.QueuedPlayers.Count}/{zone.TeamSize * 2})");
                    
                    if (zone.QueuedPlayers.Count >= zone.TeamSize * 2)
                    {
                        StartMatchFromQueue(zone);
                    }
                }
                
                EndPlayerAction(player);
            }
            catch (Exception ex)
            {
                PrintError($"Error adding player to queue: {ex.Message}");
                EndPlayerAction(player);
            }
        }
        
