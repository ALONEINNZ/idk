                var sitesToRemove = bombSites.Where(kvp => kvp.Value.MapName == mapName).Select(kvp => kvp.Key).ToList();
                foreach (var siteName in sitesToRemove)
                {
                    bombSites.Remove(siteName);
                }
                
                var zonesToRemove = queueZones.Where(kvp => kvp.Value.SelectedMap == mapName).Select(kvp => kvp.Key).ToList();
                foreach (var zoneName in zonesToRemove)
                {
                    queueZones.Remove(zoneName);
                }
                
                SaveData();
                
                SendReply(player, $"Map '{mapName}' configuration cleared!");
                SendReply(player, "Note: Physical entities must be removed manually or with other tools.");
            }
            catch (Exception ex)
            {
                PrintError($"Error clearing map: {ex.Message}");
                SendReply(player, "Error clearing map!");
            }
        }
        
