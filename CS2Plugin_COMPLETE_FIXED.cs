                if (!string.IsNullOrEmpty(data.QueueZoneName) && queueZones.ContainsKey(data.QueueZoneName))
                {
                    var zone = queueZones[data.QueueZoneName];
                    zone.QueuedPlayers.Remove(player.userID);
                    
                    data.IsInQueue = false;
                    data.QueueZoneName = "";
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error removing player from queue: {ex.Message}");
            }
        }
        
