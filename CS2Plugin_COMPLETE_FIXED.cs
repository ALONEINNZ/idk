        private void HandlePlayerDisconnectFromMatch(BasePlayer player, PlayerData data)
        {
            try
            {
                if (activeMatches.ContainsKey(data.CurrentMatchId))
                {
                    var match = activeMatches[data.CurrentMatchId];
                    
                    match.TerroristPlayers.Remove(player.userID);
                    match.CounterTerroristPlayers.Remove(player.userID);
                    
                    int remainingPlayers = match.TerroristPlayers.Count + match.CounterTerroristPlayers.Count;
                    if (remainingPlayers < 2)
                    {
                        EndMatch(match, "Insufficient players");
                    }
                    else
                    {
                        NotifyMatchPlayers(match, $"{player.displayName} has disconnected");
                    }
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error handling player disconnect from match: {ex.Message}");
            }
        }
        
