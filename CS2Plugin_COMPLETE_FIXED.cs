        private void StartMatchFromQueue(QueueZone zone)
        {
            try
            {
                if (zone.QueuedPlayers.Count < zone.TeamSize * 2)
                {
                    PrintWarning($"Not enough players to start match in zone {zone.Name}");
                    return;
                }
                
                if (activeMatches.Count >= config.MaxConcurrentMatches)
                {
                    PrintWarning("Maximum concurrent matches reached");
                    return;
                }
                
                var matchId = (ulong)UnityEngine.Random.Range(100000, 999999);
                while (activeMatches.ContainsKey(matchId))
                {
                    matchId = (ulong)UnityEngine.Random.Range(100000, 999999);
                }
                
                var match = new Match
                {
                    MatchId = matchId,
                    MapName = zone.SelectedMap,
                    State = MatchState.WaitingForPlayers,
                    QueueZoneName = zone.Name,
                    MatchStartTime = Time.time
                };
                
                var shuffledPlayers = zone.QueuedPlayers.OrderBy(x => UnityEngine.Random.value).ToList();
                
                for (int i = 0; i < zone.TeamSize && i < shuffledPlayers.Count; i++)
                {
                    match.TerroristPlayers.Add(shuffledPlayers[i]);
                }
                
                for (int i = zone.TeamSize; i < zone.TeamSize * 2 && i < shuffledPlayers.Count; i++)
                {
                    match.CounterTerroristPlayers.Add(shuffledPlayers[i]);
                }
                
                foreach (var playerId in shuffledPlayers)
                {
                    var data = GetPlayerData(playerId);
                    if (data != null)
                    {
                        data.CurrentMatchId = matchId;
                        data.IsInQueue = false;
                        data.QueueZoneName = "";
                        data.CurrentTeam = match.TerroristPlayers.Contains(playerId) ? Team.Terrorist : Team.CounterTerrorist;
                    }
                }
                
                zone.QueuedPlayers.Clear();
                activeMatches[matchId] = match;
                
                StartMatch(match);
                
                PrintWarning($"Started match {matchId} with {shuffledPlayers.Count} players");
            }
            catch (Exception ex)
            {
                PrintError($"Error starting match from queue: {ex.Message}");
            }
        }
        
        private void StartMatch(Match match)
        {
            try
            {
                if (!match.IsValid())
                {
                    PrintError($"Invalid match data for match {match.MatchId}");
                    return;
                }
                
                match.State = MatchState.InProgress;
                match.CurrentRound = 0;
                
                TeleportPlayersToSpawns(match);
                NotifyMatchPlayers(match, "Match starting! Get ready!");
                
                timer.Once(3f, () => StartRound(match));
                
                PrintWarning($"Match {match.MatchId} started on map {match.MapName}");
            }
            catch (Exception ex)
            {
                PrintError($"Error starting match: {ex.Message}");
            }
        }
        
        private void StartRound(Match match)
        {
            try
            {
                if (!activeMatches.ContainsKey(match.MatchId))
                {
                    PrintWarning($"Match {match.MatchId} no longer active");
                    return;
                }
                
                match.CurrentRound++;
                match.RoundStartTime = Time.time;
                match.IsBuyPhase = true;
                
                match.RoundTimer?.Destroy();
                match.BuyPhaseTimer?.Destroy();
                
                ResetPlayersForNewRound(match);
                TeleportPlayersToSpawns(match);
                
                match.BuyPhaseTimer = timer.Once(config.BuyPhaseDuration, () => EndBuyPhase(match));
                match.ActiveTimers.Add(match.BuyPhaseTimer);
                
                match.RoundTimer = timer.Once(120f, () => EndRound(match, RoundEndReason.TimeExpired));
                match.ActiveTimers.Add(match.RoundTimer);
                
                NotifyMatchPlayers(match, $"Round {match.CurrentRound} started! Buy phase: {config.BuyPhaseDuration} seconds");
                
                PrintWarning($"Round {match.CurrentRound} started for match {match.MatchId}");
            }
            catch (Exception ex)
            {
                PrintError($"Error starting round: {ex.Message}");
            }
        }
        
        private void EndBuyPhase(Match match)
        {
            try
            {
                if (!activeMatches.ContainsKey(match.MatchId))
                {
                    return;
                }
                
                match.IsBuyPhase = false;
                
                foreach (var playerId in match.TerroristPlayers.Concat(match.CounterTerroristPlayers))
                {
                    var player = BasePlayer.FindByID(playerId);
                    if (player != null)
                    {
                        CloseBuyMenu(player);
                    }
                }
                
                NotifyMatchPlayers(match, "Buy phase ended! Fight!");
            }
            catch (Exception ex)
            {
                PrintError($"Error ending buy phase: {ex.Message}");
            }
        }
        
        private void EndRound(Match match, RoundEndReason reason)
        {
            try
            {
                if (!activeMatches.ContainsKey(match.MatchId))
                {
                    return;
                }
                
                match.RoundTimer?.Destroy();
                match.BuyPhaseTimer?.Destroy();
                match.PlantedBomb?.ExplosionTimer?.Destroy();
                
                Team winningTeam = DetermineRoundWinner(match, reason);
                UpdateMatchScore(match, winningTeam);
                
                string reasonText = GetRoundEndReasonText(reason);
                string winnerText = winningTeam == Team.Terrorist ? "Terrorists" : "Counter-Terrorists";
                NotifyMatchPlayers(match, $"Round {match.CurrentRound} ended: {winnerText} win ({reasonText})");
                
                if (IsMatchFinished(match))
                {
                    EndMatch(match, "Match completed");
                }
                else
                {
                    if (match.CurrentRound == config.SideSwapRound && !match.HasSwappedSides)
                    {
                        SwapTeams(match);
                    }
                    
                    timer.Once(5f, () => StartRound(match));
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error ending round: {ex.Message}");
            }
        }
        
        private Team DetermineRoundWinner(Match match, RoundEndReason reason)
        {
            switch (reason)
            {
                case RoundEndReason.TerroristsEliminated:
                    return Team.CounterTerrorist;
                case RoundEndReason.CounterTerroristsEliminated:
                    return Team.Terrorist;
                case RoundEndReason.BombExploded:
                    return Team.Terrorist;
                case RoundEndReason.BombDefused:
                    return Team.CounterTerrorist;
                case RoundEndReason.TimeExpired:
                    return Team.CounterTerrorist;
                default:
                    return Team.CounterTerrorist;
            }
        }
        
        private void UpdateMatchScore(Match match, Team winningTeam)
        {
            if (winningTeam == Team.Terrorist)
            {
                match.TerroristScore++;
            }
            else if (winningTeam == Team.CounterTerrorist)
            {
                match.CounterTerroristScore++;
            }
        }
        
        private string GetRoundEndReasonText(RoundEndReason reason)
        {
            switch (reason)
            {
                case RoundEndReason.TerroristsEliminated:
                    return "All terrorists eliminated";
                case RoundEndReason.CounterTerroristsEliminated:
                    return "All counter-terrorists eliminated";
                case RoundEndReason.BombExploded:
                    return "Bomb exploded";
                case RoundEndReason.BombDefused:
                    return "Bomb defused";
                case RoundEndReason.TimeExpired:
                    return "Time expired";
                default:
                    return "Unknown";
            }
        }
        
        private bool IsMatchFinished(Match match)
        {
            return match.TerroristScore >= config.RoundWinRequirement || 
                   match.CounterTerroristScore >= config.RoundWinRequirement;
        }
        
        private void SwapTeams(Match match)
        {
            try
            {
                var tempList = new List<ulong>(match.TerroristPlayers);
                match.TerroristPlayers = new List<ulong>(match.CounterTerroristPlayers);
                match.CounterTerroristPlayers = tempList;
                
                foreach (var playerId in match.TerroristPlayers.Concat(match.CounterTerroristPlayers))
                {
                    var data = GetPlayerData(playerId);
                    if (data != null)
                    {
                        data.CurrentTeam = match.TerroristPlayers.Contains(playerId) ? Team.Terrorist : Team.CounterTerrorist;
                    }
                }
                
                match.HasSwappedSides = true;
                
                NotifyMatchPlayers(match, "Teams have been swapped!");
                
                PrintWarning($"Teams swapped for match {match.MatchId}");
            }
            catch (Exception ex)
            {
                PrintError($"Error swapping teams: {ex.Message}");
            }
        }
        
        private void EndMatch(Match match, string reason)
        {
            try
            {
                if (!activeMatches.ContainsKey(match.MatchId))
                {
                    return;
                }
                
                match.State = MatchState.Finished;
                match.CleanupTimers();
                
                Team winningTeam = match.TerroristScore > match.CounterTerroristScore ? Team.Terrorist : Team.CounterTerrorist;
                string winnerText = winningTeam == Team.Terrorist ? "Terrorists" : "Counter-Terrorists";
                
                NotifyMatchPlayers(match, $"Match ended: {winnerText} win! ({match.TerroristScore}-{match.CounterTerroristScore})");
                NotifyMatchPlayers(match, $"Reason: {reason}");
                
                foreach (var playerId in match.TerroristPlayers.Concat(match.CounterTerroristPlayers))
                {
                    var data = GetPlayerData(playerId);
                    if (data != null)
                    {
                        data.CurrentMatchId = 0;
                        data.CurrentTeam = Team.None;
                        data.IsSpectating = false;
                        data.IsInFreeCam = false;
                    }
                    
                    var player = BasePlayer.FindByID(playerId);
                    if (player != null)
                    {
                        TeleportToLobby(player);
                        CloseBuyMenu(player);
                        DestroyUI(player);
                        timer.Once(1f, () => CreateUI(player));
                    }
                }
                
                activeMatches.Remove(match.MatchId);
                
                PrintWarning($"Match {match.MatchId} ended: {reason}");
            }
            catch (Exception ex)
            {
                PrintError($"Error ending match: {ex.Message}");
            }
        }
        
