        public class QueueZone
        {
            public string Name { get; set; }
            public Vector3 MinBounds { get; set; }
            public Vector3 MaxBounds { get; set; }
            public List<ulong> QueuedPlayers { get; set; } = new List<ulong>();
            public int TeamSize { get; set; } = 5;
            public bool IsActive { get; set; } = true;
            public string SelectedMap { get; set; } = "dust2";
            public float CreatedTime { get; set; } = 0f;
            
            public bool IsValid()
            {
                return !string.IsNullOrEmpty(Name) && TeamSize > 0 && TeamSize <= 10;
            }
            
            public Vector3 GetCenter()
            {
                return (MinBounds + MaxBounds) / 2f;
            }
        }
        
        public class BombSite
        {
            public string Name { get; set; }
            public Vector3 MinBounds { get; set; }
            public Vector3 MaxBounds { get; set; }
            public string MapName { get; set; }
            public bool IsActive { get; set; } = true;
            
            public bool IsValid()
            {
                return !string.IsNullOrEmpty(Name) && !string.IsNullOrEmpty(MapName);
            }
            
            public bool ContainsPosition(Vector3 position)
            {
                return position.x >= MinBounds.x && position.x <= MaxBounds.x &&
                       position.y >= MinBounds.y && position.y <= MaxBounds.y &&
                       position.z >= MinBounds.z && position.z <= MaxBounds.z;
            }
        }
        
