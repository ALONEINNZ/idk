        private void LoadConfig()
        {
            try
            {
                config = Config.ReadObject<Configuration>();
                if (config == null) 
                {
                    PrintWarning("Config is null, loading default config");
                    LoadDefaultConfig();
                }
                ValidateConfig();
            }
            catch (Exception ex)
            {
                PrintError($"Error loading config: {ex.Message}");
                LoadDefaultConfig();
            }
        }
        
        private void ValidateConfig()
        {
            if (config.DefaultTeamSize < 1) config.DefaultTeamSize = 5;
            if (config.DefaultTeamSize > 10) config.DefaultTeamSize = 10;
            if (config.RoundWinRequirement < 1) config.RoundWinRequirement = 13;
            if (config.BuyPhaseDuration < 5f) config.BuyPhaseDuration = 20f;
            if (config.BombTimer < 10f) config.BombTimer = 40f;
            if (config.MaxTeamDamage < 100f) config.MaxTeamDamage = 300f;
            if (config.MaxQueueTime < 60f) config.MaxQueueTime = 300f;
            if (config.MaxConcurrentMatches < 1) config.MaxConcurrentMatches = 10;
        }
        
        private void SaveConfig() 
        {
            try
            {
                Config.WriteObject(config);
            }
            catch (Exception ex)
            {
                PrintError($"Error saving config: {ex.Message}");
            }
        }
        
