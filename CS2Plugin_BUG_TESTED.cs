        private PlayerData GetPlayerData(ulong playerId)
        {
            if (playerId == 0) return null; // Bug Fix: Validate player ID
            
            if (!playerData.ContainsKey(playerId))
            {
                var player = BasePlayer.FindByID(playerId);
                if (player == null) return null; // Bug Fix: Check if player exists
                
                playerData[playerId] = new PlayerData
                {
                    PlayerId = playerId,
                    PlayerName = player.displayName ?? "Unknown",
                    SafePosition = player.transform.position
                };
            }
            return playerData[playerId];
        }
        
