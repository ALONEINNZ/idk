                }
                
                // Find current index and switch to next
                int currentIndex = alivePlayers.IndexOf(spectatorData.SpectatingPlayerId);
                int nextIndex = (currentIndex + 1) % alivePlayers.Count;
                
                spectatorData.SpectatingPlayerId = alivePlayers[nextIndex];
                spectatorData.SpectatorIndex = nextIndex;
                
                var nextPlayer = BasePlayer.FindByID(spectatorData.SpectatingPlayerId);
                if (nextPlayer != null)
                {
                    SendReply(spectator, $"Now spectating: {nextPlayer.displayName}");
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error switching spectator target: {ex.Message}");
            }
        }
        
