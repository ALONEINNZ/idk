        void OnPlayerInput(BasePlayer player, InputState input)
        {
            if (player == null || input == null) return;
            
            try
            {
                if (!CanPlayerPerformAction(player)) return;
                
                var data = GetPlayerData(player.userID);
                if (data == null) return;
                
                CheckPlayerInQueueZone(player);
                
                if (data.IsSpectating && !data.IsInFreeCam)
                {
                    HandleSpectatorInput(player, input);
                }
                
                if (data.CurrentMatchId != 0 && activeMatches.ContainsKey(data.CurrentMatchId))
                {
                    var match = activeMatches[data.CurrentMatchId];
                    HandleMatchInput(player, input, match, data);
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error on player input {player?.displayName}: {ex.Message}");
            }
        }
        
        private void HandleSpectatorInput(BasePlayer player, InputState input)
        {
            try
            {
                if (input.WasJustPressed(BUTTON.FIRE_PRIMARY))
                {
                    SpectateNextPlayer(player);
                }
                else if (input.WasJustPressed(BUTTON.FIRE_SECONDARY))
                {
                    SpectatePreviousPlayer(player);
                }
                else if (input.WasJustPressed(BUTTON.USE))
                {
                    ToggleFreeCam(player);
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error handling spectator input: {ex.Message}");
            }
        }
        
        private void HandleMatchInput(BasePlayer player, InputState input, Match match, PlayerData data)
        {
            try
            {
                if (match.State == MatchState.InProgress && match.PlantedBomb != null)
                {
                    if (input.IsDown(BUTTON.USE) && data.CurrentTeam == Team.CounterTerrorist && !data.IsSpectating)
                    {
                        float distance = Vector3.Distance(player.transform.position, match.PlantedBomb.Position);
                        if (distance <= 2f)
                        {
                            StartDefuse(player, match);
                        }
                    }
                    else if (!input.IsDown(BUTTON.USE) && data.IsDefusing)
                    {
                        StopDefuse(player, match);
                    }
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error handling match input: {ex.Message}");
            }
        }
        
        private void CheckPlayerInQueueZone(BasePlayer player)
        {
            try
            {
                var data = GetPlayerData(player.userID);
                if (data == null) return;
                
                var playerPos = GetSafePosition(player.transform.position);
                
                foreach (var zone in queueZones.Values)
                {
                    if (!zone.IsActive || !zone.IsValid()) continue;
                    
                    bool inZone = IsPlayerInZone(playerPos, zone.MinBounds, zone.MaxBounds);
                    
                    if (inZone && !data.IsInQueue)
                    {
                        AddPlayerToQueue(player, zone);
                    }
                    else if (!inZone && data.IsInQueue && data.QueueZoneName == zone.Name)
                    {
                        RemovePlayerFromQueue(player.userID);
                    }
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error checking queue zone: {ex.Message}");
            }
        }
        
        private bool IsPlayerInZone(Vector3 position, Vector3 minBounds, Vector3 maxBounds)
        {
            try
            {
                return position.x >= minBounds.x && position.x <= maxBounds.x &&
                       position.y >= minBounds.y && position.y <= maxBounds.y &&
                       position.z >= minBounds.z && position.z <= maxBounds.z;
            }
            catch
            {
                return false;
            }
        }
        
        private void AddPlayerToQueue(BasePlayer player, QueueZone zone)
        {
            if (!CanPlayerPerformAction(player)) return;
            
            try
            {
                StartPlayerAction(player);
                
                var data = GetPlayerData(player.userID);
                if (data == null || data.CurrentMatchId != 0)
                {
                    EndPlayerAction(player);
                    SendReply(player, "You are already in a match!");
                    return;
                }
                
                if (zone.QueuedPlayers.Count >= zone.TeamSize * 2)
                {
                    EndPlayerAction(player);
                    SendReply(player, "Queue is full!");
                    return;
                }
                
                data.IsInQueue = true;
                data.QueueZoneName = zone.Name;
                data.QueueJoinTime = Time.time;
                zone.QueuedPlayers.Add(player.userID);
                
                SendReply(player, $"Added to queue ({zone.QueuedPlayers.Count}/{zone.TeamSize * 2})");
                
                if (zone.QueuedPlayers.Count >= zone.TeamSize * 2 && 
                    activeMatches.Count < config.MaxConcurrentMatches)
                {
                    var queuedPlayers = zone.QueuedPlayers.ToList();
                    zone.QueuedPlayers.Clear();
                    StartMatch(zone, queuedPlayers);
                }
                
                EndPlayerAction(player);
            }
            catch (Exception ex)
            {
                EndPlayerAction(player);
                PrintError($"Error adding player to queue: {ex.Message}");
            }
        }
        
        private void RemovePlayerFromQueue(ulong playerId)
        {
            try
            {
                var data = GetPlayerData(playerId);
                if (data == null || !data.IsInQueue) return;
                
                if (queueZones.ContainsKey(data.QueueZoneName))
                {
                    var zone = queueZones[data.QueueZoneName];
                    zone.QueuedPlayers.Remove(playerId);
                }
                
                data.IsInQueue = false;
                data.QueueZoneName = "";
                data.QueueJoinTime = 0f;
                
                var player = BasePlayer.FindByID(playerId);
                if (player != null)
                {
                    SendReply(player, "Removed from queue");
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error removing player from queue: {ex.Message}");
            }
        }
        
        private void StartMatch(QueueZone zone, List<ulong> queuedPlayers)
        {
            try
            {
                var matchId = (ulong)UnityEngine.Random.Range(100000, 999999);
                while (activeMatches.ContainsKey(matchId))
                {
                    matchId = (ulong)UnityEngine.Random.Range(100000, 999999);
                }
                
                var match = new Match
                {
                    MatchId = matchId,
                    MapName = zone.SelectedMap,
                    QueueZoneName = zone.Name,
                    State = MatchState.InProgress,
                    MatchStartTime = Time.time
                };
                
                var shuffledPlayers = queuedPlayers.OrderBy(x => UnityEngine.Random.value).ToList();
                for (int i = 0; i < shuffledPlayers.Count; i++)
                {
                    var playerId = shuffledPlayers[i];
                    var data = GetPlayerData(playerId);
                    if (data != null)
                    {
                        data.CurrentMatchId = matchId;
                        data.IsInQueue = false;
                        data.QueueZoneName = "";
                        data.QueueJoinTime = 0f;
                        
                        if (i < zone.TeamSize)
                        {
                            match.TerroristPlayers.Add(playerId);
                            data.CurrentTeam = Team.Terrorist;
                        }
                        else
                        {
                            match.CounterTerroristPlayers.Add(playerId);
                            data.CurrentTeam = Team.CounterTerrorist;
                        }
                    }
                }
                
                if (match.IsValid())
                {
                    activeMatches[matchId] = match;
                    NotifyMatchStart(match);
                    StartRound(match);
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error starting match: {ex.Message}");
            }
        }
        
