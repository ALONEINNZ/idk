        private void CleanupExpiredQueues()
        {
            var expiredQueues = new List<string>();
            
            foreach (var kvp in queueZones)
            {
                var zone = kvp.Value;
                var expiredPlayers = new List<ulong>();
                
                foreach (var playerId in zone.QueuedPlayers)
                {
                    var data = GetPlayerData(playerId);
                    if (data == null || !data.IsInQueue || 
                        (data.QueueJoinTime > 0 && Time.time - data.QueueJoinTime > config.MaxQueueTime))
                    {
                        expiredPlayers.Add(playerId);
                    }
                }
                
                foreach (var playerId in expiredPlayers)
                {
                    zone.QueuedPlayers.Remove(playerId);
                    var data = GetPlayerData(playerId);
                    if (data != null)
                    {
                        data.IsInQueue = false;
                        data.QueueZoneName = "";
                    }
                }
            }
        }
        
        private void CleanupInactiveMatches()
        {
            var inactiveMatches = new List<ulong>();
            
            foreach (var kvp in activeMatches)
            {
                var match = kvp.Value;
                
                // Check if match has been running too long without activity
                if (Time.time - match.MatchStartTime > 3600f) // 1 hour
                {
                    inactiveMatches.Add(kvp.Key);
                    continue;
                }
                
                // Check if all players have disconnected
                var connectedPlayers = match.TerroristPlayers.Concat(match.CounterTerroristPlayers)
                    .Count(id => BasePlayer.FindByID(id) != null);
                
                if (connectedPlayers == 0)
                {
                    inactiveMatches.Add(kvp.Key);
                }
            }
            
            foreach (var matchId in inactiveMatches)
            {
                if (activeMatches.ContainsKey(matchId))
                {
                    EndMatch(activeMatches[matchId], "Match cleanup - inactive");
                }
            }
        }
        
        private void CleanupDisconnectedPlayers()
        {
            var disconnectedPlayers = new List<ulong>();
            
            foreach (var kvp in playerData)
            {
                var playerId = kvp.Key;
                var data = kvp.Value;
                
                var player = BasePlayer.FindByID(playerId);
                if (player == null || !player.IsConnected)
                {
                    // Clean up player's match involvement
                    if (data.CurrentMatchId != 0)
                    {
                        if (activeMatches.ContainsKey(data.CurrentMatchId))
                        {
                            var match = activeMatches[data.CurrentMatchId];
                            match.TerroristPlayers.Remove(playerId);
                            match.CounterTerroristPlayers.Remove(playerId);
                        }
                    }
                    
                    // Clean up queue involvement
                    if (data.IsInQueue && !string.IsNullOrEmpty(data.QueueZoneName))
                    {
                        if (queueZones.ContainsKey(data.QueueZoneName))
                        {
                            queueZones[data.QueueZoneName].QueuedPlayers.Remove(playerId);
                        }
                    }
                    
                    // Clean up timers
                    data.DefuseTimer?.Destroy();
                    
                    disconnectedPlayers.Add(playerId);
                }
            }
            
            foreach (var playerId in disconnectedPlayers)
            {
                playerData.Remove(playerId);
            }
        }
        
