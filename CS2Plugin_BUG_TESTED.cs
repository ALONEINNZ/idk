                    data.IsInFreeCam = true;
                    data.SpectatingPlayerId = 0;
                    return;
                }
                
                // Find current index and switch to previous
                int currentIndex = alivePlayers.IndexOf(data.SpectatingPlayerId);
                int prevIndex = currentIndex <= 0 ? alivePlayers.Count - 1 : currentIndex - 1;
                
                data.SpectatingPlayerId = alivePlayers[prevIndex];
                data.SpectatorIndex = prevIndex;
                
                var prevPlayer = BasePlayer.FindByID(data.SpectatingPlayerId);
                if (prevPlayer != null)
                {
                    SendReply(player, $"Now spectating: {prevPlayer.displayName}");
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error switching to previous spectator target: {ex.Message}");
            }
        }
        
