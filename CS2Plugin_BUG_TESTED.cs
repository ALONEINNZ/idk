        private void StartRound(Match match)
        {
            try
            {
                if (!activeMatches.ContainsKey(match.MatchId))
                {
                    PrintWarning($"Match {match.MatchId} no longer active");
                    return;
                }
                
                match.CurrentRound++;
                match.RoundStartTime = Time.time;
                match.IsBuyPhase = true;
                
                // Clean up previous round timers
                match.RoundTimer?.Destroy();
                match.BuyPhaseTimer?.Destroy();
                
                // Reset player states
                ResetPlayersForNewRound(match);
                
                // Teleport players to spawns
                TeleportPlayersToSpawns(match);
                
                // Start buy phase
                match.BuyPhaseTimer = timer.Once(config.BuyPhaseDuration, () => EndBuyPhase(match));
                match.ActiveTimers.Add(match.BuyPhaseTimer);
                
                // Start round timer
                match.RoundTimer = timer.Once(120f, () => EndRound(match, RoundEndReason.TimeExpired));
                match.ActiveTimers.Add(match.RoundTimer);
                
                // Notify players
                NotifyMatchPlayers(match, $"Round {match.CurrentRound} started! Buy phase: {config.BuyPhaseDuration} seconds");
                
                PrintWarning($"Round {match.CurrentRound} started for match {match.MatchId}");
            }
            catch (Exception ex)
            {
                PrintError($"Error starting round: {ex.Message}");
            }
        }
        
