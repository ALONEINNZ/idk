        void OnPlayerDisconnected(BasePlayer player, string reason)
        {
            if (player == null) return;
            
            try
            {
                var data = GetPlayerData(player.userID);
                if (data != null)
                {
                    if (data.IsInQueue)
                    {
                        RemovePlayerFromQueue(player.userID);
                    }
                    
                    if (data.CurrentMatchId != 0 && activeMatches.ContainsKey(data.CurrentMatchId))
                    {
                        var match = activeMatches[data.CurrentMatchId];
                        PrintToChat($"{player.displayName} disconnected from match {match.MatchId}");
                    }
                    
                    // Clean up player timers
                    data.DefuseTimer?.Destroy();
                }
                
                DestroyUI(player);
                processingPlayers.Remove(player.userID);
                lastActionTime.Remove(player.userID);
            }
            catch (Exception ex)
            {
                PrintError($"Error on player disconnected {player?.displayName}: {ex.Message}");
            }
        }
        
        void OnPlayerDeath(BasePlayer victim, HitInfo info)
        {
            if (victim == null) return;
            
            try
            {
                var victimData = GetPlayerData(victim.userID);
                if (victimData?.CurrentMatchId == 0) return;
                
                if (!activeMatches.ContainsKey(victimData.CurrentMatchId)) return;
                var match = activeMatches[victimData.CurrentMatchId];
                
                if (match.State != MatchState.InProgress) return;
                
                victimData.Deaths++;
                victimData.RoundDeaths++;
                
                BasePlayer attacker = info?.InitiatorPlayer;
                if (attacker != null && attacker != victim)
                {
                    var attackerData = GetPlayerData(attacker.userID);
                    if (attackerData != null)
                    {
                        if (victimData.CurrentTeam == attackerData.CurrentTeam)
                        {
                            HandleTeamKill(attacker, victim, info);
                        }
                        else
                        {
                            attackerData.Kills++;
                            attackerData.RoundKills++;
                            PrintToChat($"{attacker.displayName} eliminated {victim.displayName}");
                        }
                    }
                }
                
                timer.Once(2f, () => MoveToSpectatorArea(victim, match));
                CheckRoundEnd(match);
            }
            catch (Exception ex)
            {
                PrintError($"Error on player death {victim?.displayName}: {ex.Message}");
            }
        }
        
        void OnPlayerRespawned(BasePlayer player)
        {
            if (player == null) return;
            
            try
            {
                var data = GetPlayerData(player.userID);
                if (data?.CurrentMatchId != 0 && activeMatches.ContainsKey(data.CurrentMatchId))
                {
                    var match = activeMatches[data.CurrentMatchId];
                    if (match.State == MatchState.InProgress && !data.IsSpectating)
                    {
                        timer.Once(0.5f, () => RestorePlayerForMatch(player, match));
                    }
                }
            }
            catch (Exception ex)
            {
                PrintError($"Error on player respawned {player?.displayName}: {ex.Message}");
            }
        }
        
