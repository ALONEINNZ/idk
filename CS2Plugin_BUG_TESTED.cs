                    if (data.CurrentMatchId != 0 && activeMatches.ContainsKey(data.CurrentMatchId))
                    {
                        var match = activeMatches[data.CurrentMatchId];
                        if (match.State == MatchState.InProgress)
                        {
                            timer.Once(2f, () => HandlePlayerReconnection(player, match));
                        }
                    }
                    
                    timer.Once(1f, () => CreateUI(player));
                }
