        private void CmdJoinQueue(BasePlayer player, string command, string[] args)
        {
            var data = GetPlayerData(player.userID);
            
            if (data.IsInQueue)
            {
                SendReply(player, "You are already in a queue!");
                return;
            }
            
            if (data.CurrentMatchId != 0)
            {
                SendReply(player, "You are already in a match!");
                return;
            }
            
            // Find nearest queue zone
            QueueZone nearestZone = null;
            float nearestDistance = float.MaxValue;
            
            foreach (var zone in queueZones.Values)
            {
                if (!zone.IsActive) continue;
                
                var center = (zone.MinBounds + zone.MaxBounds) / 2f;
                float distance = Vector3.Distance(player.transform.position, center);
                
                if (distance < nearestDistance)
                {
                    nearestDistance = distance;
                    nearestZone = zone;
                }
            }
            
            if (nearestZone == null)
            {
                SendReply(player, "No queue zones available!");
                return;
            }
            
            AddPlayerToQueue(player, nearestZone);
        }
        
