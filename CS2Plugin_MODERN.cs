        private void AutoGenerateServerMaps()
        {
            PrintWarning("Starting automatic map generation for large Rust map...");
            
            // Check if we already have maps configured
            if (mapConfigurations.Count > 2)
            {
                PrintWarning("Maps already exist, skipping auto-generation.");
                return;
            }
            
            // Detect map size and adjust accordingly
            float mapSize = GetMapSize();
            PrintWarning($"Detected map size: {mapSize}");
            
            if (mapSize >= 2000f) // Large map
            {
                GenerateMultipleCompetitiveZones();
            }
            else
            {
                GenerateSingleCompetitiveZone();
            }
            
            PrintWarning("Automatic map generation completed!");
        }
        
        private float GetMapSize()
        {
            try
            {
                if (TerrainMeta.Size != null)
                {
                    return TerrainMeta.Size.x;
                }
            }
            catch
            {
                // Fallback for older versions
            }
            
            // Default assumption for large maps
            return 2900f;
        }
        
        private void GenerateMultipleCompetitiveZones()
        {
            PrintWarning("Generating multiple competitive zones for large map...");
            
            float mapSize = GetMapSize();
            float radius = mapSize * 0.3f; // 30% of map size
            
            // Generate 4 competitive zones in different quadrants
            var zones = new List<Vector3>
            {
                new Vector3(radius * 0.5f, 0, radius * 0.5f),      // NE
                new Vector3(-radius * 0.5f, 0, radius * 0.5f),     // NW
                new Vector3(radius * 0.5f, 0, -radius * 0.5f),     // SE
                new Vector3(-radius * 0.5f, 0, -radius * 0.5f)     // SW
            };
            
            for (int i = 0; i < zones.Count; i++)
            {
                Vector3 center = FindSafeLocation(zones[i]);
                GenerateCompetitiveZone($"zone_{i + 1}", center, i);
            }
        }
        
        private void GenerateSingleCompetitiveZone()
        {
            PrintWarning("Generating single competitive zone...");
            
            Vector3 center = config.MapGenerationCenter;
            if (center == Vector3.zero)
            {
                center = FindSafeLocation(Vector3.zero);
            }
            
            GenerateCompetitiveZone("main_zone", center, 0);
        }
        
        private Vector3 FindSafeLocation(Vector3 preferredLocation)
        {
            Vector3 bestLocation = preferredLocation;
            
            try
            {
                // Try to find a location that's not in water and has reasonable terrain
                for (int attempts = 0; attempts < 10; attempts++)
                {
                    Vector3 testLocation = preferredLocation + new Vector3(
                        UnityEngine.Random.Range(-200f, 200f),
                        0,
                        UnityEngine.Random.Range(-200f, 200f)
                    );
                    
                    // Get terrain height
                    float height = GetTerrainHeight(testLocation);
                    testLocation.y = height;
                    
                    // Check if location is suitable
                    if (IsLocationSuitable(testLocation))
                    {
                        bestLocation = testLocation;
                        break;
                    }
                }
            }
            catch (Exception ex)
            {
                PrintWarning($"Error finding safe location: {ex.Message}");
            }
            
            return bestLocation;
        }
        
        private float GetTerrainHeight(Vector3 position)
        {
            try
            {
                if (TerrainMeta.HeightMap != null)
                {
                    return TerrainMeta.HeightMap.GetHeight(position);
                }
            }
            catch
            {
                // Fallback for older versions
            }
            
            // Use raycast as fallback
            RaycastHit hit;
            if (Physics.Raycast(position + Vector3.up * 200f, Vector3.down, out hit, 400f, LayerMask.GetMask("Terrain")))
            {
                return hit.point.y;
            }
            
            return 0f;
        }
        
        private bool IsLocationSuitable(Vector3 location)
        {
            try
            {
                // Check if in water
                if (WaterLevel.Test(location))
                {
                    return false;
                }
                
                // Check for existing entities
                var entities = new List<BaseEntity>();
                Vis.Entities(location, 50f, entities);
                
                // Too many existing structures
                if (entities.Count > 20)
                {
                    return false;
                }
                
                return true;
            }
            catch
            {
                return true; // Assume suitable if checks fail
            }
        }
        
        private void GenerateCompetitiveZone(string zoneName, Vector3 center, int zoneIndex)
        {
            PrintWarning($"Generating competitive zone: {zoneName} at {center}");
            
            // Create map configuration
            var mapConfig = new MapConfiguration
            {
                MapName = zoneName,
                SpectatorArea = center + Vector3.up * 20f
            };
            
            // Generate spawn points
            GenerateSpawnPoints(mapConfig, center);
            
            // Generate bomb sites
            GenerateBombSites(mapConfig, center);
            
            // Generate structures
            GenerateMapStructures(center, zoneName);
            
            // Save configuration
            mapConfigurations[zoneName] = mapConfig;
            
            // Create queue zone
            CreateQueueZone(zoneName, center);
            
            PrintWarning($"Zone {zoneName} generated successfully!");
        }
        
        private void GenerateSpawnPoints(MapConfiguration mapConfig, Vector3 center)
        {
            // Terrorist spawns (one side)
            for (int i = 0; i < 8; i++)
            {
                Vector3 spawnPos = center + new Vector3(-60f + i * 3f, 0, -80f);
                spawnPos.y = GetTerrainHeight(spawnPos) + 1f;
                mapConfig.TerroristSpawns.Add(spawnPos);
            }
            
            // Counter-Terrorist spawns (opposite side)
            for (int i = 0; i < 8; i++)
            {
                Vector3 spawnPos = center + new Vector3(-60f + i * 3f, 0, 80f);
                spawnPos.y = GetTerrainHeight(spawnPos) + 1f;
                mapConfig.CounterTerroristSpawns.Add(spawnPos);
            }
        }
        
        private void GenerateBombSites(MapConfiguration mapConfig, Vector3 center)
        {
            // Bomb site A
            Vector3 siteA = center + new Vector3(-40f, 0, 40f);
            siteA.y = GetTerrainHeight(siteA);
            
            string siteAName = $"{mapConfig.MapName}_A";
            bombSites[siteAName] = new BombSite
            {
                Name = siteAName,
                MapName = mapConfig.MapName,
                MinBounds = siteA - Vector3.one * 8f,
                MaxBounds = siteA + Vector3.one * 8f,
                IsActive = true
            };
            mapConfig.BombSiteNames.Add(siteAName);
            
            // Bomb site B
            Vector3 siteB = center + new Vector3(40f, 0, -40f);
            siteB.y = GetTerrainHeight(siteB);
            
            string siteBName = $"{mapConfig.MapName}_B";
            bombSites[siteBName] = new BombSite
            {
                Name = siteBName,
                MapName = mapConfig.MapName,
                MinBounds = siteB - Vector3.one * 8f,
                MaxBounds = siteB + Vector3.one * 8f,
                IsActive = true
            };
            mapConfig.BombSiteNames.Add(siteBName);
        }
        
        private void GenerateMapStructures(Vector3 center, string mapName)
        {
            try
            {
                // Generate basic structures using modern Rust entities
                CreateWalls(center);
                CreateCover(center);
                CreateLighting(center);
            }
            catch (Exception ex)
            {
                PrintWarning($"Error generating structures for {mapName}: {ex.Message}");
            }
        }
        
        private void CreateWalls(Vector3 center)
        {
            // Create walls using modern building blocks
            var wallPositions = new List<Vector3>
            {
                center + new Vector3(-50f, 0, 0),
                center + new Vector3(50f, 0, 0),
                center + new Vector3(0, 0, -50f),
                center + new Vector3(0, 0, 50f)
            };
            
            foreach (var pos in wallPositions)
            {
                Vector3 groundPos = pos;
                groundPos.y = GetTerrainHeight(pos);
                
                // Create wall entity
                var wall = GameManager.server.CreateEntity("assets/prefabs/building core/wall/wall.prefab", groundPos);
                if (wall != null)
                {
                    wall.Spawn();
                }
            }
        }
        
