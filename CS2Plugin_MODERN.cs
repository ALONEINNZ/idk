        private void CreateQueueZone(string mapName, Vector3 center)
        {
            Vector3 queueCenter = center + new Vector3(0, 0, -120f);
            queueCenter.y = GetTerrainHeight(queueCenter);
            
            queueZones[mapName + "_queue"] = new QueueZone
            {
                Name = mapName + "_queue",
                MinBounds = queueCenter - new Vector3(10f, 5f, 10f),
                MaxBounds = queueCenter + new Vector3(10f, 5f, 10f),
                TeamSize = config.DefaultTeamSize,
                IsActive = true,
                SelectedMap = mapName
            };
            
            PrintWarning($"Queue zone created for {mapName} at {queueCenter}");
        }
        
        private void DetectMapCenter()
        {
            if (config.MapGenerationCenter != Vector3.zero) return;
            
            try
            {
                // Try to get map bounds
                if (TerrainMeta.Bounds.size != Vector3.zero)
                {
                    config.MapGenerationCenter = TerrainMeta.Bounds.center;
                }
                else
                {
                    config.MapGenerationCenter = Vector3.zero;
                }
            }
            catch
            {
                config.MapGenerationCenter = Vector3.zero;
            }
            
            SaveConfig();
            PrintWarning($"Map center detected: {config.MapGenerationCenter}");
        }
        
