        private void NotifyMatchStart(Match match)
        {
            var allPlayers = match.TerroristPlayers.Concat(match.CounterTerroristPlayers);
            
            foreach (var playerId in allPlayers)
            {
                var player = BasePlayer.FindByID(playerId);
                if (player != null)
                {
                    SendReply(player, $"Match {match.MatchId} started! Map: {match.MapName}");
                    SendReply(player, $"First to {config.RoundWinRequirement} rounds wins!");
                }
            }
        }
        
        private void StartRound(Match match)
        {
            match.CurrentRound++;
            match.RoundStartTime = Time.time;
            match.IsBuyPhase = true;
            match.PlantedBomb = null;
            
            // Reset round stats for all players
            var allPlayers = match.TerroristPlayers.Concat(match.CounterTerroristPlayers);
            foreach (var playerId in allPlayers)
            {
                var data = GetPlayerData(playerId);
                data.RoundKills = 0;
                data.RoundDeaths = 0;
            }
            
            // Check for side swap
            if (match.CurrentRound == config.SideSwapRound + 1 && !match.HasSwappedSides)
            {
                SwapTeams(match);
            }
            
            // Teleport players to spawns
            TeleportPlayersToSpawns(match);
            
            // Give satchel to terrorists
            GiveSatchelToTerrorists(match);
            
            // Start buy phase timer
            match.BuyPhaseTimer = timer.Once(config.BuyPhaseDuration, () => EndBuyPhase(match));
            
            // Start round timer
            float roundDuration = 120f;
            match.RoundTimer = timer.Once(roundDuration, () => EndRound(match, RoundEndReason.TimeExpired));
            
            NotifyRoundStart(match);
        }
        
        private void SwapTeams(Match match)
        {
            match.HasSwappedSides = true;
            
            foreach (var playerId in match.TerroristPlayers.ToList())
            {
                var data = GetPlayerData(playerId);
                data.CurrentTeam = Team.CounterTerrorist;
            }
            
            foreach (var playerId in match.CounterTerroristPlayers.ToList())
            {
                var data = GetPlayerData(playerId);
                data.CurrentTeam = Team.Terrorist;
            }
            
            var tempList = match.TerroristPlayers.ToList();
            match.TerroristPlayers = match.CounterTerroristPlayers.ToList();
            match.CounterTerroristPlayers = tempList;
            
            NotifyTeamSwap(match);
        }
        
        private void TeleportPlayersToSpawns(Match match)
        {
            if (!mapConfigurations.ContainsKey(match.MapName)) return;
            
            var mapConfig = mapConfigurations[match.MapName];
            
            for (int i = 0; i < match.TerroristPlayers.Count; i++)
            {
                var player = BasePlayer.FindByID(match.TerroristPlayers[i]);
                if (player != null && i < mapConfig.TerroristSpawns.Count)
                {
                    TeleportPlayer(player, mapConfig.TerroristSpawns[i]);
                    GetPlayerData(player.userID).IsSpectating = false;
                }
            }
            
            for (int i = 0; i < match.CounterTerroristPlayers.Count; i++)
            {
                var player = BasePlayer.FindByID(match.CounterTerroristPlayers[i]);
                if (player != null && i < mapConfig.CounterTerroristSpawns.Count)
                {
                    TeleportPlayer(player, mapConfig.CounterTerroristSpawns[i]);
                    GetPlayerData(player.userID).IsSpectating = false;
                }
            }
        }
        
        private void TeleportPlayer(BasePlayer player, Vector3 position)
        {
            if (player == null) return;
            
            player.Teleport(position);
            player.SendNetworkUpdateImmediate();
        }
        
        private void GiveSatchelToTerrorists(Match match)
        {
            foreach (var playerId in match.TerroristPlayers)
            {
                var player = BasePlayer.FindByID(playerId);
                if (player != null && !player.IsDead())
                {
                    GiveItem(player, "explosive.satchel", 1);
                    SendReply(player, "You have the bomb! Plant it at a bomb site.");
                    break;
                }
            }
        }
        
        private void EndBuyPhase(Match match)
        {
            match.IsBuyPhase = false;
            
            var allPlayers = match.TerroristPlayers.Concat(match.CounterTerroristPlayers);
            foreach (var playerId in allPlayers)
            {
                var player = BasePlayer.FindByID(playerId);
                if (player != null)
                {
                    var data = GetPlayerData(playerId);
                    if (data.HasBuyMenuOpen)
                    {
                        CloseBuyMenu(player);
                    }
                    SendReply(player, "Buy phase ended!");
                }
            }
        }
        
